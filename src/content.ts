export const catalog = cases
  .filter(
    (item, index) =>
      cases.findIndex((other) => other.official === item.official) === index,
  )
  .map((item) => ({
    official: item.official,
    line: item.bits[0] ?? "",
  }));

export function caseById(id: string) {
  return cases.find((item) => item.id === id);
}

